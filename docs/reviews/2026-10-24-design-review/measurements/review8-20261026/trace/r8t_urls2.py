import duckdb
base="/Users/mikewolfd/Work/congressional-tech/.cache/congressional-tech-raw/indexes/"
con=duckdb.connect()
c=f"read_parquet('{base}captures.parquet')"
q=lambda s: con.execute(s).fetchall()
print("--- congress.gov/<c>/meeting/ samples:")
for r in q(f"select distinct context_url from {c} where regexp_matches(context_url,'congress\\.gov/[0-9]+/meeting/') limit 4"): print("  ",r[0])
print("govinfo /zip (api) distinct:", q(f"select count(distinct context_url) from {c} where regexp_matches(context_url,'govinfo\\.gov/.*/zip')")[0][0])
print("govinfo /zip sample:", q(f"select distinct context_url from {c} where regexp_matches(context_url,'govinfo\\.gov/.*/zip') limit 2"))
print("--- odd-length CHRG jackets:")
for r in q(f"select regexp_extract(context_url,'(CHRG-[0-9]+[hsj]hrg[0-9]+)',1) p, min(context_url) from {c} where length(regexp_extract(context_url,'CHRG-[0-9]+[hsj]hrg([0-9]+)',1)) in (7,8,9) or regexp_matches(context_url,'CHRG-[0-9]+[hsj]hrg0') group by 1 order by 1 limit 8"): print("  ",r)
print("--- retained-file rows: context_url host distribution:")
for r in q(f"select regexp_extract(context_url,'^[a-z]+://([^/]+)',1) h, count(*) from {c} where reference_kind='retained-file' group by 1 order by 2 desc limit 8"): print("  ",r)
print("retained-file rows with retrieved_at:", q(f"select count(*) from {c} where reference_kind='retained-file' and retrieved_at is not null and retrieved_at<>''")[0][0])
print("--- documents index: recovered_source_url vs source_url equality on rows with recovered_filename:")
d=f"read_parquet('{base}documents.parquet')"
print(q(f"select count(*), count(*) filter (where source_url = recovered_source_url[1]), count(*) filter (where source_url is null) from {d} where len(recovered_filename)>0"))
print("--- record_role values in documents index:")
for r in q(f"select unnest(record_role) rr, count(*) from {d} group by 1 order by 2 desc limit 15"): print("  ",r)
print("--- source_chamber values:")
for r in q(f"select unnest(source_chamber) v, count(*) from {d} group by 1 order by 2 desc limit 10"): print("  ",r)
print("--- source_meeting_id samples:")
