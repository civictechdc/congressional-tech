"""The maintained review selector is optional, detached and bound to full rows."""
from copy import deepcopy

import pytest

from congress_api.retention.document_reviews import (
    REVIEW_SOURCE, apply_review_candidate, review_group_digest,
)


def baseline():
    source=dict(source_id='s',document_id='d',body_key='retained-body',filename='amendment.pdf',
        source_occurrences=[{'label':['Café',None,'Café'],'missing':None}])
    document=dict(document_id='d',document_kind=['amendment'],document_family=['amendment'],
        filename_document_kind=['amendment'],document_kind_source=['filename'])
    review=dict(document_id='d',group_sha256=review_group_digest(document,[source]),
        original_row_sha256='original-row-digest',receipt='verified-receipt.json',receipt_sha256='verified-receipt-digest',
        body_key='retained-body',body_sha256='verified-body-digest',observed_forms=['committee-vote'],
        primary_forms=['committee-vote'],component_forms=[],reviewer='assistant',
        independent_reference=False,release_approved=False)
    return document,[source],review


def test_digest_keeps_existing_wire_encoding_and_semantic_values():
    document,sources,_=baseline()
    # Generated by the committed experiment implementation at 2045e60.
    expected='19a29a10958b1e73fb04f095375fde41e0c9fa298f57e1d5deadf49cb8798dbf'
    assert review_group_digest(document,sources)==expected
    assert review_group_digest(dict(document,null=None),sources)==expected
    changed=deepcopy(sources);changed[0]['source_occurrences'][0]['label']=['Café','Café',None]
    assert review_group_digest(document,changed)!=expected
    changed[0]['source_occurrences'][0]['label']=['Café',None]
    assert review_group_digest(document,changed)!=expected


@pytest.mark.parametrize('mode',['no_review','applied','changed_scope','unsupported'])
def test_optional_selection_preserves_baseline_and_returns_detached_evidence(mode):
    document,sources,review=baseline()
    if mode=='no_review':review=None
    elif mode=='changed_scope':sources[0]['filename']='changed.pdf'
    elif mode=='unsupported':
        review['observed_forms'].append('tax-return');review['component_forms'].append('tax-return')
    before=deepcopy((document,sources,review))
    result=apply_review_candidate(document,sources,review)
    assert result['status']==dict(no_review='no_review',applied='candidate_applied',
        changed_scope='scope_changed',unsupported='annotation_only_unsupported_forms')[mode]
    assert (document,sources,review)==before
    assert result['production_selected'] is result['release_approved'] is result['independent_reference'] is False
    if mode=='applied':
        assert result['document']['document_kind']==['committee-vote']
        assert result['document']['document_family']==['vote-record']
        assert result['document']['filename_document_kind']==['amendment']
        assert result['document']['document_kind_source']==[REVIEW_SOURCE]
    else:assert result['document']==document
    result['document']['filename_document_kind'].append('external-mutation')
    if review is not None:result['review']['observed_forms'].append('external-mutation')
    assert (document,sources,review)==before
    assert apply_review_candidate(document,sources)['document']==document


@pytest.mark.parametrize('change',['duplicate','foreign_member','previous_candidate'])
def test_invalid_baselines_refuse_reuse(change):
    document,sources,review=baseline()
    if change=='duplicate':sources.append(deepcopy(sources[0]))
    elif change=='foreign_member':sources[0]['document_id']='foreign'
    else:document=apply_review_candidate(document,sources,review)['document']
    with pytest.raises(ValueError):apply_review_candidate(document,sources)


@pytest.mark.parametrize('change',['reviewer','approval','reference','empty_forms','duplicate_forms','missing_component'])
def test_invalid_compiled_review_is_rejected(change):
    document,sources,review=baseline()
    if change=='reviewer':review['reviewer']='unverified'
    elif change=='approval':review['release_approved']=True
    elif change=='reference':review['independent_reference']=True
    elif change=='empty_forms':review['observed_forms']=[]
    elif change=='duplicate_forms':review['observed_forms']*=2
    else:review['component_forms']=['tax-return']
    with pytest.raises(ValueError):apply_review_candidate(document,sources,review)
