def __getattr__(name: str) -> Any:
    # Lazy-load `pilot` symbols so `python -m congress_docmeta.v7.factory.pilot` avoids runpy warnings.
    if name in _PILOT_EXPORTS:
        pilot_mod = importlib.import_module(".pilot", __name__)
        return getattr(pilot_mod, name)
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")


