@pytest.mark.parametrize('name,family,subject,measure,preserve', NLP_CASES)
def test_named_legislative_wording_preserves_other_components(engine,name,family,subject,measure,preserve):
    result=engine.extract(name)
    row=result['metadata']
    assert row['subject_token'] == [subject]
    assert measure in row['measure_references']
    if family == 'amendment':
        assert 'amendment' in row['document_kind']
        assert any(x.lower() == 'amendment' for x in row['amendment_marker'])
    else:
        assert any(x.lower() == 'substitute' for x in row['qualifier_wording'])
        assert not row.get('version_token')
    assert not row.get('sponsor_bioguide_id')
    for field,values in preserve.items():
        assert set(values) <= set(row.get(field,[]))
    assert_spans(result,name)

